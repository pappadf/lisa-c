#!/usr/bin/env python3
"""Generate lisa/traps.h from data/entries.tsv.

For every intrinsic-library entry point, defines LISA_TRAP_<LINKNAME> as the
two instruction words of an IUJSR to its jump vector ($A0xx, $xxxx), for use
with LISA_IU() in the Lisa headers.  Link names are the 8-character,
upper-case names of the library's EntryPoint records; characters that are not
valid in a C identifier ('%') are written as '_'.

usage: gen_traps.py data/entries.tsv out.h
"""
import sys

rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[1]) if not l.startswith('#')]
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by tools/gen_traps.py from data/entries.tsv -- do not edit. */\n')
    f.write('#ifndef LISA_TRAPS_H\n#define LISA_TRAPS_H\n')
    for lib, seg, link, addr in rows:
        a = int(addr, 16)
        name = link.upper().replace('%', '_')
        f.write(f'#define LISA_TRAP_{name} 0x{0xA000 | (a >> 16):04X}, 0x{a & 0xFFFF:04X}'
                f'   /* {lib} {seg} */\n')
    f.write('#endif\n')
